SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
ACTOR_RE = re.compile(r"^(human|agent|process):[a-z0-9._-]+$")
# [text](target) or [text](target "title"); images are matched too and filtered by caller.
LINK_RE = re.compile(r"(!?)\[([^\]]*)\]\(<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\)")
FENCE_RE = re.compile(r"^(```|~~~).*?^\1", re.M | re.S)

RELATED_START = "<!-- related:start (generated by scripts/lint.py — do not edit) -->"
RELATED_END = "<!-- related:end -->"
RELATED_RE = re.compile(re.escape(RELATED_START) + r".*?" + re.escape(RELATED_END) + r"\n?", re.S)



def slugify(text: str) -> str:
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


# --- frontmatter -------------------------------------------------------------

class FrontmatterError(Exception):
    pass


def split_frontmatter(text: str) -> tuple[str | None, str]:
    """Return (yaml_text, body). yaml_text is None when there is no frontmatter."""
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---\n", 3)
    if end == -1:
        if text.endswith("\n---"):
            return text[4:-4], ""
        raise FrontmatterError("frontmatter is not closed with '---'")
    return text[4:end + 1], text[end + 5:]


def parse_frontmatter(text: str) -> tuple[dict | None, str]:
    raw, body = split_frontmatter(text)
    if raw is None:
        return None, body
    try:
        data = yaml.safe_load(raw)
    except yaml.YAMLError as e:
        raise FrontmatterError(f"invalid YAML: {e}".replace("\n", " ")) from e
    if data is None:
        data = {}
    if not isinstance(data, dict):
        raise FrontmatterError("frontmatter must be a YAML mapping")
    return data, body


# --- schemas -----------------------------------------------------------------

@dataclass
class Schema:
    type: str
    dir: str
    path: str
    description: str
    fields: dict
    body: str
    file: Path
    scopes: tuple[str, ...] = ("root",)

    def ref_fields(self) -> list[tuple[str, dict]]:
        return [(k, f) for k, f in self.fields.items()
                if f.get("type") == "ref" or (f.get("type") == "list" and f.get("of") == "ref")]


@dataclass
class Schemas:
    common: dict
    by_type: dict[str, Schema] = field(default_factory=dict)

    def by_dir(self, dir_name: str) -> Schema | None:
        """The first schema (by file name) stored in dir_name; Idea, Plan and Result share 'ideas'."""
        return next((s for s in self.by_type.values() if s.dir == dir_name), None)

    def by_name(self, name: str) -> Schema | None:
        """Look up a schema by type ('Person'), file stem ('person') or dir ('people')."""
        for s in self.by_type.values():
            if name.lower() in (s.type.lower(), s.file.stem, s.dir):
                return s
        return None


def load_schemas() -> Schemas:
    common = yaml.safe_load((SCHEMAS / "_common.yaml").read_text(encoding="utf-8"))["fields"]
    schemas = Schemas(common=common)
    for f in sorted(SCHEMAS.glob("*.yaml")):
        if f.name.startswith("_"):
            continue
        d = yaml.safe_load(f.read_text(encoding="utf-8"))
        schemas.by_type[d["type"]] = Schema(
            type=d["type"], dir=d["dir"], path=d.get("path", "{slug}"),
            description=d.get("description", ""), fields=d.get("fields") or {},
            body=d.get("body", ""), file=f, scopes=tuple(d.get("scopes") or ("root",)),
        )
    return schemas


# --- locations ---------------------------------------------------------------

@dataclass(frozen=True)
class Location:
    """Where a file or folder sits in brain/.

    brain/meetings/2026/x.md            -> project=None,             dir='meetings', inner=('2026', 'x.md')
    brain/projects/p/meetings/2026/x.md -> project='projects/p/p',   dir='meetings', inner=('2026', 'x.md')
    brain/projects/p/p.md               -> project=None,             dir='projects', inner=('p', 'p.md')
    """
    project: str | None  # concept ID of the owning project (project scope only)
    dir: str             # schema dir; '' for the bundle root itself
    inner: tuple[str, ...]

    @property
    def scope(self) -> str:
        return "project" if self.project else "root"


def project_id(slug: str) -> str:
    return f"{PROJECTS_DIR}/{slug}/{slug}"


def locate(path: Path) -> Location:
    parts = path.relative_to(BRAIN).parts
    if len(parts) >= 3 and parts[0] == PROJECTS_DIR and not parts[2].endswith(".md"):
        return Location(project_id(parts[1]), parts[2], parts[3:])
    return Location(None, parts[0] if parts else "", parts[1:])


# --- links -------------------------------------------------------------------

def strip_code(body: str) -> str:
    """Remove fenced code blocks and inline code so example links aren't checked."""
    body = FENCE_RE.sub("", body)
    return re.sub(r"`[^`\n]*`", "", body)


def iter_links(body: str):
    """Yield (text, target) for local markdown links, skipping URLs and anchors."""
    for m in LINK_RE.finditer(strip_code(body)):
        target = m.group(3)
        if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith("#"):
            continue
        yield m.group(2), target.split("#", 1)[0]


def resolve_link(src: Path, target: str) -> Path:
    """Resolve a link target found in src. '/x' is relative to the bundle root (OKF §6.1)."""
    from urllib.parse import unquote
    target = unquote(target)
    if target.startswith("/"):
        return (BRAIN / target.lstrip("/")).resolve()
    return (src.parent / target).resolve()


def rel_link(src: Path, dst: Path) -> str:
    return Path(os.path.relpath(dst, src.parent)).as_posix()


def concept_id(path: Path) -> str:
    return path.relative_to(BRAIN).with_suffix("").as_posix()
