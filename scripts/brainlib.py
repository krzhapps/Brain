def set_root(root: Path) -> None:
    """Point every path at another repo root (used by the lint test fixtures)."""
    global ROOT, BRAIN, SCHEMAS, TEMPLATES, SESSIONS
    ROOT = root.resolve()
    BRAIN, SCHEMAS, TEMPLATES = ROOT / "brain", ROOT / "schemas", ROOT / "templates"
    SESSIONS = ROOT / "resources" / "sessions"


